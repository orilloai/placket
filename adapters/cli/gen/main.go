// Command gen writes docs/reference/cli.md, the command line's reference, from the command table of
// adapters/cli and the error table of adapters/errtext. It reads spec/protocol.md for the headings of
// the requirements each command's --json object follows, which the page links and never restates.
// adapters/cli's tests fail when the committed page differs from a fresh run.
//
// Run from the repository's root: go run ./adapters/cli/gen [-o docs/reference/cli.md] [-spec spec/protocol.md].
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"github.com/orilloai/placket/adapters/cli"
	"github.com/orilloai/placket/adapters/errtext"
)

// specLink is the requirement text, from the page's directory.
const specLink = "../../spec/protocol.md"

// The requirements the page links besides each command's: section 11, and what a verifier is given.
const (
	section11 = "11. What the command line prints for a script"
	verify1   = "verify-1"
)

// headingRE is a heading of the requirement text.
var headingRE = regexp.MustCompile(`^#{1,6}[ \t]+(.*?)[ \t#]*$`)

// slugDropRE is what GitHub drops from a heading to make its anchor.
var slugDropRE = regexp.MustCompile(`[^a-z0-9 _-]`)

// slug is the anchor GitHub gives a heading: its text in lower case, backquotes and other marks
// dropped, each space a hyphen.
func slug(text string) string {
	return strings.ReplaceAll(slugDropRE.ReplaceAllString(strings.ToLower(text), ""), " ", "-")
}

// anchors maps each requirement id of the text, and section 11's title, to its heading's anchor.
func anchors(spec []byte) map[string]string {
	out := map[string]string{}
	for _, l := range strings.Split(string(spec), "\n") {
		m := headingRE.FindStringSubmatch(l)
		if m == nil {
			continue
		}
		out[m[1]] = slug(m[1])
		if id, _, ok := strings.Cut(m[1], " "); ok {
			out[id] = slug(m[1])
		}
	}
	return out
}

// shared are the keys of the error table whose codes the command line prints: its own, the journal's,
// and those of the packages it calls and the window's replies. placket mcp's own are not.
func shared(from string) bool { return from != errtext.FromMCP }

func cell(s string) string { return strings.ReplaceAll(strings.ReplaceAll(s, "|", `\|`), "\n", " ") }

func code(s string) string { return "`" + s + "`" }

func render(spec map[string]string) ([]byte, error) {
	link := func(id string) (string, error) {
		a, ok := spec[id]
		if !ok {
			return "", fmt.Errorf("spec/protocol.md has no heading for %s", id)
		}
		return specLink + "#" + a, nil
	}
	sec11, err := link(section11)
	if err != nil {
		return nil, err
	}
	v1, err := link(verify1)
	if err != nil {
		return nil, err
	}
	c1, err := link("commands-1")
	if err != nil {
		return nil, err
	}
	rows := cli.Table()
	names := map[string]bool{}
	for _, r := range rows {
		names[strings.Join(r.Words, " ")] = true
	}

	var b bytes.Buffer
	b.WriteString(`# The command line

<!-- Generated by go run ./adapters/cli/gen from adapters/cli and adapters/errtext; do not edit. -->

Every command of ` + "`placket`" + `: what it does, its usage, its arguments and flags, what its ` + "`--json`" + ` object follows, and the exit codes it ends with. A command prints prose for a person on standard error, and JSON or a body on standard output. A command that is refused or fails ends standard error with one line: ` + "`rejected <code>`" + ` when the window refused the call, ` + "`rejected founding <code>`" + ` when it refused an acceptance, ` + "`door <code>`" + ` when the window's door refused it, and ` + "`error <code>`" + ` for any other, with any detail after the code. [Errors](#errors) gives each code's cause and fix.

With ` + "`--json`" + `, every command but ` + "`mcp`" + ` and ` + "`watch`" + ` prints its result as one JSON object and a line feed on standard output instead; its exit code and standard error stay the same. ` + "`watch`" + `, which runs until it is stopped, prints one object per question, each on a line of its own as the question opens, and then its own object. ` + "`mcp`" + `, whose standard output carries the MCP protocol, takes no ` + "`--json`" + `. Each command's object holds the members [section 11 of the protocol](` + sec11 + `) gives it, under the requirement ids each command below cites.

In a usage, ` + "`<socket flags>`" + ` stands for ` + "`--key <file> --socket <path> --accord <id>`" + `, or ` + "`--label <label>`" + ` in their place, and then ` + "`[--state <dir>]`" + `: the flags of every command that calls a window. A flag in square brackets is optional, ` + "`|`" + ` separates flags of which one is given, and ` + "`...`" + ` after a flag means it may be given more than once.

` + "`placket <command> --help`" + ` prints a command's flags on standard output, each with the sentence this page gives it, and exits 0 ([commands-1](` + c1 + `)).

## Exit codes

| Code | What it means |
|---|---|
`)
	for _, e := range cli.Exits() {
		fmt.Fprintf(&b, "| `%d` | %s |\n", e.Code, cell(e.Sentence))
	}
	b.WriteString("\n## Commands\n\n| Command | What it does |\n|---|---|\n")
	for _, r := range rows {
		n := strings.Join(r.Words, " ")
		fmt.Fprintf(&b, "| [`%s`](#%s) | %s |\n", n, slug(n), cell(r.Summary))
	}
	b.WriteString("\n")
	for _, r := range rows {
		if err := command(&b, r, names, link); err != nil {
			return nil, err
		}
	}

	b.WriteString(`## Errors

Every code the command line prints, by where it comes from: its own codes under ` + "`adapters/cli`" + `; the journal's under ` + "`adapters/journal`" + `; a code in the window's reply by its member, ` + "`door`" + `, ` + "`rejection`" + ` or ` + "`error`" + `; and any other by the package that declares it. The same code under two keys has two sentences, each saying what it means there. ` + "`placket mcp`" + `'s own codes are in the [mediator API's errors](mediator-api.md#errors).

Two kinds of code follow another and are not listed here. After ` + "`error verify`" + `, the verifier's code is the protocol's ([verify-1](` + v1 + `)). After ` + "`error judge`" + `, a judge config's code is the one ` + "`docs/adr/0023-judges.md`" + ` names. A founding code after ` + "`founding`" + ` is the protocol's too.

| From | Code | Cause and fix |
|---|---|---|
`)
	for _, r := range errtext.Rows() {
		if shared(r.From) {
			fmt.Fprintf(&b, "| `%s` | `%s` | %s |\n", r.From, r.Code, cell(r.Sentence))
		}
	}
	return b.Bytes(), nil
}

// command writes one command's section.
func command(b *bytes.Buffer, r cli.Row, names map[string]bool, link func(string) (string, error)) error {
	n := strings.Join(r.Words, " ")
	fmt.Fprintf(b, "## `%s`\n\n%s\n\n", n, r.Summary)
	usage := "placket " + n
	if r.Usage != "" {
		usage += " " + r.Usage
	}
	fmt.Fprintf(b, "Usage: `%s`\n\n", usage)
	var subs []string
	for m := range names {
		if w, ok := strings.CutPrefix(m, n+" "); ok && !strings.Contains(w, " ") {
			subs = append(subs, m)
		}
	}
	sort.Strings(subs)
	if len(subs) > 0 {
		var links []string
		for _, a := range r.Args {
			for _, v := range a.Values {
				if names[n+" "+v] {
					links = append(links, "[`"+n+" "+v+"`](#"+slug(n+" "+v)+")")
				}
			}
		}
		if len(links) == 0 {
			for _, s := range subs {
				links = append(links, "[`"+s+"`](#"+slug(s)+")")
			}
		}
		fmt.Fprintf(b, "Its subcommands: %s.\n\n", strings.Join(links, ", "))
	}
	if len(r.Args) > 0 {
		b.WriteString("| Argument | Values | What it is |\n|---|---|---|\n")
		for _, a := range r.Args {
			var vs []string
			for _, v := range a.Values {
				vs = append(vs, code(v))
			}
			fmt.Fprintf(b, "| `<%s>` | %s | %s |\n", a.Name, strings.Join(vs, ", "), cell(a.Sentence))
		}
		b.WriteString("\n")
	}
	label := false
	for _, f := range r.Flags {
		label = label || f.Name == "label" && strings.Contains(r.Usage, "<socket flags>")
	}
	if len(r.Flags) > 0 {
		b.WriteString("| Flag | Required | Default | What it is |\n|---|---|---|---|\n")
		for _, f := range r.Flags {
			req := "no"
			switch {
			case f.Required:
				req = "yes"
			case label && (f.Name == "key" || f.Name == "socket" || f.Name == "accord"):
				req = "unless `--label`"
			}
			def := ""
			switch {
			case f.DefaultArg && len(r.Args) > 0:
				def = code("<" + r.Args[0].Name + ">")
			case f.Default != "":
				def = code(f.Default)
			}
			fmt.Fprintf(b, "| `%s` | %s | %s | %s |\n", f, req, def, cell(f.Sentence))
		}
		b.WriteString("\n")
	}
	switch {
	case len(r.JSON) > 0:
		var ids []string
		for _, id := range r.JSON {
			l, err := link(id)
			if err != nil {
				return err
			}
			ids = append(ids, "["+id+"]("+l+")")
		}
		fmt.Fprintf(b, "Its `--json` object follows %s.\n\n", strings.Join(ids, ", "))
	case len(r.Flags) > 0:
		b.WriteString("It takes no `--json`: its standard output carries the MCP protocol.\n\n")
	}
	var exits []string
	for _, e := range r.Exits {
		exits = append(exits, code(strconv.Itoa(e)))
	}
	fmt.Fprintf(b, "Exit codes: %s.\n\n", strings.Join(exits, ", "))
	return nil
}

func main() {
	out := flag.String("o", filepath.Join("docs", "reference", "cli.md"), "the page to write")
	specPath := flag.String("spec", filepath.Join("spec", "protocol.md"), "the requirement text")
	flag.Parse()
	spec, err := os.ReadFile(*specPath)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	page, err := render(anchors(spec))
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.MkdirAll(filepath.Dir(*out), 0o755); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, page, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
